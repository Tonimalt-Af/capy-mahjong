function lanternLayers(): string[][] {
  const L: string[][] = [];
  const paint = (z: number, rows: string[]) => {
    if (!L[z]) L[z] = Array.from({ length: 5 }, () => '.........');
    rows.forEach((row, j) => [...row].forEach((ch, i) => {
      if (ch !== '#') return;
      const a = L[z][j].split(''); a[i] = '#'; a[i + 5] = '#'; L[z][j] = a.join('');
    }));
  };
  const one = [
    ['.##.', '####', '####', '####', '.##.'],
    ['....', '####', '####', '####', '....'],
    ['....', '.##.', '####', '####', '....'],
    ['....', '.##.', '###.', '.##.', '....'],
  ];
  one.forEach((rows, z) => paint(z, rows));
  return L;
}

RAW.lanterne = lanternLayers();

/** World 1 shapes stay as drawn. Rack layouts grow a column tall enough to hide a whole group. */
const CLASSIC_SHAPE = new Set(['carotte', 'nenuphar', 'canard', 'coeur', 'fleur']);

function raiseForRack(pos: Pos[]): Pos[] {
  const grouped = () => {
    const m = new Map<string, Pos[]>();
    for (const p of pos) { const k = `${p.x},${p.y}`; (m.get(k) ?? m.set(k, []).get(k)!).push(p); }
    return [...m.values()];
  };
  const tall = () => grouped().filter((c) => c.length >= 4).length;
  if (tall() >= 2) return pos;
  const donors = grouped().filter((c) => c.length === 1).map((c) => c[0]);
  const hosts = grouped().filter((c) => c.length >= 2 && c.length < 4).sort((a, b) => b.length - a.length);
  const stealTop = (host: Pos[]) => {
    const victim = hosts.find((c) => c !== host && c.length > 2);
    if (!victim) return;
    const top = victim.slice().sort((a, b) => b.z - a.z)[0];
    victim.splice(victim.indexOf(top), 1);
    donors.push(top);
  };
  for (const host of hosts) {
    if (tall() >= 2) break;
    while (host.length < 4) {
      if (!donors.length) stealTop(host);
      if (!donors.length) break;
      const d = donors.pop()!;
      d.x = host[0].x; d.y = host[0].y; d.z = Math.max(...host.map((p) => p.z)) + 1;
      host.push(d);
    }
  }
  return pos;
}

/** Recognisable compact silhouettes. Upper layers only sit on tiles of the layer below. */
export function silhouette(id: string): Pos[] {
  const layers = RAW[id];
  if (!layers) throw new Error(id);
  const pos = grid(...layers.map((rows, z) => [z, 0, 0, rows] as [number, number, number, string[]]));
  return CLASSIC_SHAPE.has(id) ? pos : raiseForRack(pos);
}
