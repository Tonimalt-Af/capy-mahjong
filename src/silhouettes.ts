function lanternLayers(): string[][] {
  const L: string[][] = [];
  const paint = (z: number, rows: string[]) => {
    if (!L[z]) L[z] = Array.from({ length: 5 }, () => '.........');
    rows.forEach((row, j) => [...row].forEach((ch, i) => {
      if (ch !== '#') return;
      const a = L[z][j].split(''); a[i] = '#'; a[i + 5] = '#'; L[z][j] = a.join('');
    }));
  };
  const one = [
    ['.##.', '####', '####', '####', '.##.'],
    ['....', '####', '####', '####', '....'],
    ['....', '.##.', '####', '####', '....'],
    ['....', '.##.', '###.', '.##.', '....'],
  ];
  one.forEach((rows, z) => paint(z, rows));
  return L;
}

RAW.lanterne = lanternLayers();

/** Recognisable compact silhouettes. Upper layers only sit on tiles of the layer below. */
export function silhouette(id: string): Pos[] {
  const layers = RAW[id];
  if (!layers) throw new Error(id);
  return grid(...layers.map((rows, z) => [z, 0, 0, rows] as [number, number, number, string[]]));
}
